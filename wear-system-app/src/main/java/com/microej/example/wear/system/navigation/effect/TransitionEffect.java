/**
 * Enumerates transition effects.
 */
public enum TransitionEffect {

	/** No transition effect. */
	NONE,

	/** Slide-left transition effect. */
	SLIDE_LEFT,

	/** Slide-right transition effect. */
	SLIDE_RIGHT,

	/** Slide-up transition effect. */
	SLIDE_UP,

	/** Slide-down transition effect. */
	SLIDE_DOWN
}
